    defect_percent = EXCLUDED.defect_percent;

SELECT setval(pg_get_serial_sequence('product_types', 'product_type_id'), (SELECT MAX(product_type_id) FROM product_types));
SELECT setval(pg_get_serial_sequence('material_types', 'material_type_id'), (SELECT MAX(material_type_id) FROM material_types));

COMMIT;
