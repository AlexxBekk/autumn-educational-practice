BEGIN;

CREATE TABLE IF NOT EXISTS product_types (
    product_type_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name        VARCHAR(255) NOT NULL UNIQUE,
    coefficient      DECIMAL(6,2) NOT NULL CHECK (coefficient > 0)
);

CREATE TABLE IF NOT EXISTS material_types (
    material_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name        VARCHAR(255) NOT NULL UNIQUE,
    defect_percent   DECIMAL(5,2) NOT NULL CHECK (defect_percent >= 0)
);

INSERT INTO product_types (product_type_id, type_name, coefficient) VALUES
